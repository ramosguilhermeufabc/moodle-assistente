namespace local_assistente\application\llm;

use local_assistente\infrastructure\moodle\course_section_reader;

/**
 * Builds the instruction sent to the LLM, with the language of the answer (DEC-46 D1).
 *
 * Content generated by the LLM (material summaries, forum summaries and difficulties, syntheses) is written in the forced
 * language of the course when there is one, otherwise in the default language of the site. The language used is the one the
 * caller must record in the context of the analysis. Existing content is not regenerated or translated when the language changes.
 *
 * The text of the task itself (the prompt of each use) is written by the delivery that uses it (Q-009-05); this class only
 * adds the language directive.
 *
 * Moodle API: through course_section_reader::generation_language() (forced language of the course, else the site language).
 *
 * @package    local_assistente
 * @copyright  2026
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class instruction_builder {
    /** @var course_section_reader */
    private course_section_reader $sections;

    /**
     * Constructor.
     *
     * @param course_section_reader|null $sections
     */
    public function __construct(?course_section_reader $sections = null) {
        $this->sections = $sections ?? new course_section_reader();
    }

    /**
     * Language of the content generated for a course.
     *
     * @param int $courseid
     * @return string Moodle language code, such as pt_br or en
     */
    public function language_for(int $courseid): string {
        return $this->sections->generation_language($courseid);
    }

    /**
     * Instruction for a course: the task and the language directive.
     *
     * @param int $courseid
     * @param string $task text of the task of the use
     * @return string
     */
    public function for_course(int $courseid, string $task): string {
        return self::with_language($task, $this->language_for($courseid));
    }

    /**
     * Add the language directive to a task text.
     *
     * @param string $task
     * @param string $language Moodle language code
     * @return string
     * @throws \InvalidArgumentException when the task or the language is empty
     */
    public static function with_language(string $task, string $language): string {
        if (trim($task) === '' || trim($language) === '') {
            throw new \InvalidArgumentException('The task and the language must not be empty.');
        }
        return rtrim($task) . "\n\nWrite the whole answer in the language with Moodle code '" . trim($language) . "'.";
    }
}
