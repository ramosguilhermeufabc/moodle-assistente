namespace local_assistente\output;

use PHPUnit\Framework\Attributes\CoversClass;

/**
 * Tests of the renderables and the templates (quickstart 021 Q2, Q3, Q7, Q8, Q9 and Q12; DEC-24, DEC-35 D2, DEC-41, DEC-42 D3, DEC-46).
 *
 * The rows are the ones a query returns. The real Moodle renderer renders the real Mustache templates, so what is checked is the HTML
 * that the browser receives.
 *
 * @package    local_assistente
 * @copyright  2026
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
#[CoversClass(query_page::class)]
#[CoversClass(report_page::class)]
#[CoversClass(history_page::class)]
#[CoversClass(table_data::class)]
#[CoversClass(renderer::class)]
final class renderables_test extends \advanced_testcase {
    /**
     * The plugin renderer.
     *
     * @return renderer
     */
    private function renderer(): renderer {
        global $PAGE;
        return $PAGE->get_renderer('local_assistente');
    }

    /**
     * Render a query page for a list of rows.
     *
     * @param array $rows
     * @return string
     */
    private function html_of(array $rows): string {
        return $this->renderer()->render(new query_page('Notas', ['available' => true, 'message' => null, 'rows' => $rows]));
    }

    /**
     * Q7: the values no_data, error and a valid zero are shown as the texts of DEC-24, in a native table.
     */
    public function test_states_are_shown_as_text_in_a_native_table(): void {
        $this->resetAfterTest();
        $html = $this->html_of([
            ['id' => 1, 'name' => 'Ana', 'course_total' => ['state' => 'valid', 'text' => '0,00%']],
            ['id' => 2, 'name' => 'Bia', 'course_total' => ['state' => 'no_data', 'text' => get_string('query:no_data', 'local_assistente')]],
            ['id' => 3, 'name' => 'Caio', 'course_total' => ['state' => 'error', 'text' => get_string('query:error', 'local_assistente')]],
        ]);

        $this->assertStringContainsString('<table class="generaltable', $html);
        $this->assertStringContainsString('<th scope="col">', $html);
        $this->assertStringContainsString('<th scope="row">', $html);
        $this->assertStringContainsString('0,00%', $html);
        $this->assertStringContainsString(get_string('query:no_data', 'local_assistente'), $html);
        $this->assertStringContainsString(get_string('query:error', 'local_assistente'), $html);
        $this->assertStringNotContainsString('<input', $html, 'No field: there is no chat (Q4)');
        $this->assertStringNotContainsString('<textarea', $html);
    }

    /**
     * Q3 and Q8: the notes of a removed source and of a coverage without materials are shown.
     */
    public function test_removed_source_and_no_materials_are_visible(): void {
        $this->resetAfterTest();
        $removed = get_string('query:source_removed', 'local_assistente');
        $nomaterials = get_string('query:no_materials', 'local_assistente');
        $html = $this->html_of([
            ['cmid' => 4, 'quiz' => 'Prova 1', 'coverage' => ['state' => 'no_data', 'text' => $nomaterials], 'status' => ['state' => 'valid', 'text' => $removed]],
        ]);

        $this->assertStringContainsString($nomaterials, $html);
        $this->assertStringContainsString($removed, $html);
    }

    /**
     * Q9: a text generated by the LLM with markup is shown as text, escaped.
     */
    public function test_generated_text_is_escaped(): void {
        $this->resetAfterTest();
        $html = $this->html_of([
            ['section_id' => 9, 'section' => 'Seção <i>1</i>', 'content' => '<script>alert(1)</script> e <b>negrito</b>'],
        ]);

        $this->assertStringNotContainsString('<script>', $html);
        $this->assertStringNotContainsString('<b>negrito</b>', $html);
        $this->assertStringContainsString('&lt;script&gt;alert(1)&lt;/script&gt;', $html);
        $this->assertStringContainsString('&lt;b&gt;negrito&lt;/b&gt;', $html);
        $this->assertStringContainsString('Seção &lt;i&gt;1&lt;/i&gt;', $html);
    }

    /**
     * Q12 and Q11: the stored content is shown as it was generated, in its own language, while the labels follow the language of the user.
     */
    public function test_stored_content_keeps_its_language_and_labels_follow_the_user(): void {
        $this->resetAfterTest();
        $user = $this->getDataGenerator()->create_user(['lang' => 'en']);
        $this->setUser($user);
        $html = $this->html_of([['section_id' => 1, 'section' => 'Section 1', 'content' => 'Síntese gerada em português.']]);

        $this->assertStringContainsString('Síntese gerada em português.', $html);
        $this->assertStringContainsString('Content', $html, 'The label is in the language of the user');
        $this->assertStringContainsString('Section', $html);
    }

    /**
     * A message of "assistant not enabled" replaces the table, and an available query without rows says there is no data.
     */
    public function test_unavailable_and_empty(): void {
        $this->resetAfterTest();
        $message = get_string('query:not_enabled', 'local_assistente');
        $html = $this->renderer()->render(new query_page('Notas', ['available' => false, 'message' => $message, 'rows' => []]));
        $this->assertStringContainsString($message, $html);
        $this->assertStringNotContainsString('<table', $html);

        $empty = $this->renderer()->render(new query_page('Notas', ['available' => true, 'message' => null, 'rows' => []]));
        $this->assertStringContainsString(get_string('query:no_data', 'local_assistente'), $empty);
        $this->assertStringNotContainsString('<table', $empty);
    }

    /**
     * Q2: the report shows the current version with a link to the history, and a table for each block.
     */
    public function test_report_shows_the_current_version_with_the_link_to_the_history(): void {
        $this->resetAfterTest();
        $result = ['available' => true, 'message' => null, 'rows' => [[
            'version' => 3, 'type' => 'final', 'generated_at' => 1900000000,
            'blocks' => [
                'grades' => ['state' => 'valid', 'rows' => [['id' => 1, 'name' => 'Ana', 'course_total' => ['state' => 'valid', 'text' => '66,66%']]]],
                'forums' => ['state' => 'no_data', 'rows' => []],
            ],
        ]]];
        $html = $this->renderer()->render(new report_page($result, new \moodle_url('/local/assistente/index.php', ['id' => 2, 'tab' => 'history'])));

        $this->assertStringContainsString(get_string('report:current_version', 'local_assistente', 3), $html);
        $this->assertStringContainsString('href="https://www.example.com/moodle/local/assistente/index.php?id=2&amp;tab=history"', $html);
        $this->assertStringContainsString('66,66%', $html);
        $this->assertStringContainsString(get_string('block:forums', 'local_assistente'), $html);
        $this->assertStringContainsString(get_string('query:no_data', 'local_assistente'), $html);

        $none = $this->renderer()->render(new report_page(['available' => true, 'message' => null, 'rows' => []], new \moodle_url('/x')));
        $this->assertStringContainsString(get_string('report:none', 'local_assistente'), $none);
    }

    /**
     * The history lists a row for each version, with the date and whether it is the current one.
     */
    public function test_history_lists_the_versions(): void {
        $this->resetAfterTest();
        $html = $this->renderer()->render(new history_page('Histórico', ['available' => true, 'message' => null, 'rows' => [
            ['type' => 'synthesis', 'version' => 2, 'analysis_id' => 8, 'created_at' => 1900000000, 'current' => true, 'content' => 'B', 'source' => ['state' => 'valid', 'text' => null]],
            ['type' => 'synthesis', 'version' => 1, 'analysis_id' => 5, 'created_at' => 1890000000, 'current' => false, 'content' => 'A', 'source' => ['state' => 'valid', 'text' => null]],
        ]]));

        $this->assertStringContainsString(get_string('yes'), $html);
        $this->assertStringContainsString(get_string('no'), $html);
        $this->assertStringContainsString(userdate(1900000000, get_string('strftimedatetimeshort')), $html);
        $this->assertStringNotContainsString('analysis_id', $html);
    }
    /**
     * Item 11 (Q-020-02): when a filter leaves nothing, the page says that no version matches the filters; without a filter an empty result
     * keeps the messages it had.
     */
    public function test_no_results_for_a_filter_has_its_own_message(): void {
        $this->resetAfterTest();
        $found = get_string('filter:no_results', 'local_assistente');
        $empty = ['available' => true, 'message' => null, 'rows' => []];

        $history = $this->renderer()->render(new history_page('Histórico', $empty, true));
        $this->assertStringContainsString($found, $history);
        $this->assertStringNotContainsString(get_string('query:no_data', 'local_assistente'), $history);
        $this->assertStringNotContainsString('<table', $history);
        $this->assertStringContainsString(
            get_string('query:no_data', 'local_assistente'),
            $this->renderer()->render(new history_page('Histórico', $empty, false))
        );

        $report = $this->renderer()->render(new report_page($empty, new \moodle_url('/x'), true));
        $this->assertStringContainsString($found, $report);
        $this->assertStringNotContainsString(get_string('report:none', 'local_assistente'), $report);
        $this->assertStringContainsString(
            get_string('report:none', 'local_assistente'),
            $this->renderer()->render(new report_page($empty, new \moodle_url('/x'), false))
        );
        $this->assertStringNotContainsString($found, $this->renderer()->render(new query_page('Notas', $empty)));
    }
}
